_kiwi = None


def _engine():
    global _kiwi
    if _kiwi is None:
        _kiwi = Kiwi()
        for t in TERMS:
            try:
                _kiwi.add_user_word(t, 'NNG', 5.0)
            except Exception:
                pass
    return _kiwi


# 한글이 거의 없는(수식/표) 조각은 건드리지 않는다
_HAN = re.compile(r'[가-힣]')
_JAMO_ONLY = re.compile(r'^[ㄱ-ㅎㅏ-ㅣ0-9\s,.·~\-()]+$')


@lru_cache(maxsize=200000)
def _space_cached(s):
    return _engine().space(s)


def respace(s):
    """문자열의 띄어쓰기를 복원한다. 수식·기호 조각은 원본 유지."""
    if not s:
        return s
    s = s.strip()
    han = len(_HAN.findall(s))
    # 한글이 2자 미만이거나 자모 나열(ㄱ,ㄴ,ㄷ)이면 그대로 둔다
    if han < 2 or _JAMO_ONLY.match(s):
        return s
    # 한글 비중이 지나치게 낮으면(수식 위주) 그대로 둔다
    if han / len(s) < 0.35:
        return s
    try:
        out = _space_cached(s)
    except Exception:
        return s
    # 교정 결과가 원본 글자를 잃어버렸다면 되돌린다 (안전장치)
    if re.sub(r'\s', '', out) != re.sub(r'\s', '', s):
        return s
    return out


# ── OCR 자모 깨짐 복원 ──────────────────────────────
# 보기 나열에서 ㄱ→7, ㄹ→2, ㄴ→L, ㄷ→c, ㅁ→□ 로 자주 깨진다
_JAMO_CTX = re.compile(r'^[ㄱ-ㅎ0-9A-Za-z□\s,.·~\-()]+$')
_MAP = {'7': 'ㄱ', '2': 'ㄹ', 'L': 'ㄴ', 'l': 'ㄴ', 'c': 'ㄷ', 'C': 'ㄷ',
        '□': 'ㅁ', 'ㅁ': 'ㅁ', 'ㄹ': 'ㄹ'}


def fix_jamo(s):
    """'7,ㄴ,2' → 'ㄱ,ㄴ,ㄹ' 처럼 자모 나열의 OCR 오인식을 복원한다."""
    if not s:
        return s
    t = s.strip()
    # 자모가 하나라도 있고 전체가 자모/숫자/기호로만 이루어진 짧은 나열일 때만
    if len(t) > 24 or not _JAMO_CTX.match(t):
        return s
    if not re.search(r'[ㄱ-ㅎ]', t):
        return s
    return ''.join(_MAP.get(ch, ch) for ch in t)


def fix_jamo_lead(s):
    """'2.연구전반에 대한 지침' 처럼 지문 항목 머리글자만 깨진 경우를 복원한다."""
    return re.sub(r'^([7２2Ll□cC])\s*([.,)])', lambda m: _MAP.get(m.group(1), m.group(1)) + m.group(2), s.strip())
